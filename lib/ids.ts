import * as Crypto from 'expo-crypto';

/**
 * Το id ενός μηνύματος, φτιαγμένο στη συσκευή πριν φύγει το μήνυμα.
 *
 * Το φτιάχνει ο client και όχι η βάση, ώστε το μήνυμα να έχει ταυτότητα από την
 * πρώτη στιγμή που εμφανίζεται στην οθόνη. Από εκεί βγαίνουν δύο πράγματα που
 * αλλιώς θα ήταν δύσκολα:
 *
 *  - Όταν γυρίσει το realtime echo, έχει ΤΟ ΙΔΙΟ id — οπότε ο έλεγχος διπλών
 *    που ήδη υπάρχει το αναγνωρίζει, χωρίς να μαντεύουμε από περιεχόμενο και ώρα.
 *  - Το retry ξαναστέλνει το ίδιο id. Αν το πρώτο insert είχε περάσει και χάθηκε
 *    μόνο η απάντηση, το δεύτερο σκοντάφτει στο primary key αντί να γράψει
 *    δεύτερη φορά το μήνυμα.
 *
 * Το expo-crypto και όχι το crypto.randomUUID(): το τελευταίο δεν υπάρχει στο
 * Hermes, δηλαδή θα έσκαγε στο κινητό ενώ θα δούλευε στο web.
 */
export function newMessageId(): string {
  return Crypto.randomUUID();
}
